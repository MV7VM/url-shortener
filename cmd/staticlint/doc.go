// Package main provides a custom static analysis multichecker used in this
// project. The multichecker aggregates a set of analyzers from different
// sources and can be run via go vet's -vettool flag.
//
// # Запуск multichecker'а
//
// Бинарь staticlint собирается из пакета cmd/staticlint:
//
//	go build -o staticlint ./cmd/staticlint
//
// Затем его можно запустить двумя основными способами.
//
//  1. Как отдельную утилиту анализа:
//
//     ./staticlint ./...
//
//     В этом режиме multichecker анализирует все пакеты, указанные в
//     аргументах (например, ./..., ./internal/..., ./cmd/shortener и т. д.).
//
//  2. Как плагин для go vet:
//
//     go vet -vettool=$(pwd)/staticlint ./...
//
//     В этом случае go vet использует staticlint вместо стандартного
//     набора анализаторов и передаёт ему тот же список пакетов, что и
//     обычно.
//
// # Состав multichecker'а
//
// Multichecker включает несколько групп анализаторов.
//
//   - Стандартные анализаторы из пакета golang.org/x/tools/go/analysis/passes:
//     asmdecl, assign, atomic, bools, buildtag, cgocall, composite,
//     copylock, errorsas, httpresponse, loopclosure, nilfunc, printf,
//     shadow, shift, stdmethods, stringintconv, structtag,
//     testinggoroutine, unmarshal, unreachable, unsafeptr, unusedresult.
//     Они проверяют корректность использования стандартной библиотеки,
//     формат строк, теги структур, возможные гонки данных и другие
//     типичные ошибки, которые обычно проверяет go vet.
//
//   - Все анализаторы класса SA из пакета staticcheck
//     (honnef.co/go/tools/staticcheck). Это семейство правил SAxxxx,
//     направленных на поиск потенциальных багов и проблем с
//     корректностью кода: неправильные аргументы функций, подозрительные
//     сравнения, ошибки при работе с каналами, горутинами, синхронизацией
//     и т. п. В multichecker включены все анализаторы, чьё имя начинается
//     с "SA".
//
//   - Не менее одного анализатора из других классов Staticcheck:
//
//   - S1000 (пакет honnef.co/go/tools/simple): упрощение кода,
//     поиск избыточных конструкций, которые можно записать короче
//     или понятнее.
//
//   - ST1000 (пакет honnef.co/go/tools/stylecheck): проверка стиля
//     и, в частности, выбор хороших имён для пакетов.
//
//   - Внешние публичные анализаторы:
//
//   - github.com/kisielk/errcheck/errcheck.Analyzer — проверяет, что
//     результаты функций, возвращающие ошибку, не игнорируются без
//     явного решения; помогает не пропустить важные ошибки.
//
//   - github.com/gordonklaus/ineffassign/pkg/ineffassign.Analyzer —
//     находит неэффективные присваивания переменным, значения
//     которых далее нигде не используются.
//
//   - Собственный анализатор проекта: noosexitAnalyzer.
//
// # Анализатор noosexitAnalyzer
//
// Анализатор noosexitAnalyzer (Name: "noosexit") запрещает прямой
// вызов os.Exit в функции main пакета main. Он просматривает только
// пакеты с именем "main" и ищет топ‑уровневую функцию main без
// получателя. Внутри её тела он анализирует все вызовы функций и
// с помощью информации типов (types.Info) определяет, является ли
// вызываемая функция именно os.Exit из стандартного пакета os.
//
// При обнаружении такого вызова анализатор сообщает диагностическое
// сообщение. Идея состоит в том, чтобы заставить приложение возвращать
// коды ошибок через обычные механизмы (возврат значения, обработка
// ошибок, логирование), а не завершать процесс немедленно из глубин
// приложения. Это упрощает тестирование, повторное использование
// и композицию программы.
//
// Таким образом, multichecker объединяет:
//
//   - стандартные проверки go vet;
//   - расширенный набор правил Staticcheck (все SA‑анализаторы и
//     выбранные правила simple/stylecheck);
//   - дополнительные публичные анализаторы errcheck и ineffassign;
//   - доменно‑специфичный анализатор noosexitAnalyzer, описывающий
//     архитектурное ограничение проекта.
package main
